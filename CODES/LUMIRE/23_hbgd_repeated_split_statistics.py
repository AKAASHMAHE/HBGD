def exact_binomial_two_sided(
    successes,
    trials
):
    """
    Exact two-sided binomial test against p=0.5.

    Implemented manually for Python 3.6 compatibility.
    """

    if trials == 0:
        return np.nan

    def choose(n, k):

        return math.factorial(n) / (
            math.factorial(k)
            *
            math.factorial(n - k)
        )

    observed_prob = (
        choose(trials, successes)
        *
        (0.5 ** trials)
    )

    p_value = 0.0

    for k in range(
        trials + 1
    ):

        prob = (
            choose(trials, k)
            *
            (0.5 ** trials)
        )

        if prob <= (
            observed_prob + 1e-15
        ):

            p_value += prob

    return min(
        1.0,
        p_value
    )


def percentile_ci(
    values,
    low=2.5,
    high=97.5
):

    return (
        np.percentile(
            values,
            low
        ),
        np.percentile(
            values,
            high
        )
    )


