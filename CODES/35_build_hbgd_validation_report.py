section("STEP 33 - CT TO HBGD CNN PROTOTYPE")

df = results["step33"]

if df is not None:

    print(
        "CNN prediction records:",
        len(df)
    )

    rate_col_pred = None
    rate_col_true = None

    for c in df.columns:

        lc = c.lower()

        if (
            "pred" in lc
            and "rate" in lc
        ):
            rate_col_pred = c

        if (
            ("true" in lc or "target" in lc)
            and "rate" in lc
        ):
            rate_col_true = c

    if (
        rate_col_pred is not None
        and rate_col_true is not None
    ):

        pred = pd.to_numeric(
            df[rate_col_pred],
            errors="coerce"
        )

        true = pd.to_numeric(
            df[rate_col_true],
            errors="coerce"
        )

        mask = (
            pred.notna()
            &
            true.notna()
        )

        if mask.any():

            err = pred[mask] - true[mask]

            print(
                "Rate MAE:",
                fmt(
                    np.mean(
                        np.abs(err)
                    ),
                    6
                )
            )

    print(
        "\nIMPORTANT:"
    )

    print(
        "Step 33 contained only one independent "
        "testing trajectory."
    )

    print(
        "Therefore it is a prototype demonstration, "
        "not model validation."
    )


